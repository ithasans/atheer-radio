final localeProvider = StateNotifierProvider<LocaleNotifier, String>((ref) {
  return LocaleNotifier();
});

class LocaleNotifier extends StateNotifier<String> {
  static const String _key = 'app_language_code';

  LocaleNotifier() : super('ar') {
    _loadLocale();
  }

  Future<void> _loadLocale() async {
    final prefs = await SharedPreferences.getInstance();
    final savedLocale = prefs.getString(_key);
    if (savedLocale != null && (savedLocale == 'ar' || savedLocale == 'en' || savedLocale == 'de')) {
      state = savedLocale;
    }
  }

  Future<void> setLocale(String langCode) async {
    if (langCode != 'ar' && langCode != 'en' && langCode != 'de') return;
    state = langCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_key, langCode);
  }

  Future<void> toggleLocale() async {
    final next = state == 'ar' ? 'en' : (state == 'en' ? 'de' : 'ar');
    await setLocale(next);
  }
}

